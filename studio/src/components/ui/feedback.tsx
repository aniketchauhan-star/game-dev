import type { ReactNode } from 'react';
import { CircleAlert, CircleCheck, Info, Sparkles, TriangleAlert, User, FlaskConical, FileText } from 'lucide-react';
import type { Provenance } from '@shared/schemas/common.ts';
import type { StatusLabel } from '@shared/schemas/project.ts';

export function Spinner({ large, label }: { large?: boolean; label?: string }) {
  return (
    <span className="row" role={label ? 'status' : undefined}>
      <span className={`spinner${large ? ' spinner-lg' : ''}`} aria-hidden="true" />
      {label && <span className="muted small">{label}</span>}
    </span>
  );
}

type Tone = 'info' | 'warning' | 'danger' | 'success' | 'ai';
const ICONS: Record<Tone, ReactNode> = {
  info: <Info size={18} aria-hidden="true" />,
  warning: <TriangleAlert size={18} aria-hidden="true" />,
  danger: <CircleAlert size={18} aria-hidden="true" />,
  success: <CircleCheck size={18} aria-hidden="true" />,
  ai: <Sparkles size={18} aria-hidden="true" />,
};

export function Banner({ tone = 'info', title, children, actions, role }: { tone?: Tone; title?: ReactNode; children?: ReactNode; actions?: ReactNode; role?: 'alert' | 'status' }) {
  return (
    <div className={`banner banner-${tone}`} role={role ?? (tone === 'danger' ? 'alert' : undefined)}>
      {ICONS[tone]}
      <div className="banner-body">
        {title && <p className="banner-title">{title}</p>}
        {children && <div className="banner-text">{children}</div>}
        {actions && <div className="banner-actions">{actions}</div>}
      </div>
    </div>
  );
}

export function EmptyState({ icon, title, children, actions, className }: { icon: ReactNode; title: string; children?: ReactNode; actions?: ReactNode; className?: string }) {
  return (
    <div className={['empty', className].filter(Boolean).join(' ')}>
      <div className="empty-icon" aria-hidden="true">
        {icon}
      </div>
      <h3>{title}</h3>
      {children && <p>{children}</p>}
      {actions && <div className="row-wrap" style={{ justifyContent: 'center' }}>{actions}</div>}
    </div>
  );
}

const STATUS_TONE: Record<StatusLabel, string> = {
  Draft: 'pill-neutral',
  'Content reviewed': 'pill-info',
  'Blueprint approved': 'pill-ai',
  Playable: 'pill-success',
  'Needs attention': 'pill-warning',
};

export function StatusPill({ label }: { label: StatusLabel }) {
  return <span className={`pill ${STATUS_TONE[label]}`}>{label}</span>;
}

export function Pill({ tone = 'neutral', children, dot = true }: { tone?: 'neutral' | 'info' | 'success' | 'warning' | 'danger' | 'ai'; children: ReactNode; dot?: boolean }) {
  return <span className={`pill pill-${tone}${dot ? '' : ' pill-nodot'}`}>{children}</span>;
}

/** Where a piece of content came from: the creator, Claude, the demo fixtures or the deck itself. */
export function OriginBadge({ origin, model }: { origin: Provenance | 'claude' | 'demo' | 'creator'; model?: string | null }) {
  if (origin === 'demo') return <DemoBadge />;
  const map = {
    claude: { cls: 'is-claude', icon: <Sparkles size={13} aria-hidden="true" />, text: `Claude${model ? ` · ${model}` : ''}` },
    creator: { cls: 'is-creator', icon: <User size={13} aria-hidden="true" />, text: 'Creator' },
    extracted: { cls: '', icon: <FileText size={13} aria-hidden="true" />, text: 'From the deck' },
    system: { cls: '', icon: <Info size={13} aria-hidden="true" />, text: 'System' },
  } as const;
  const m = map[origin as keyof typeof map] ?? map.system;
  return (
    <span className={`badge-origin ${m.cls}`}>
      {m.icon}
      {m.text}
    </span>
  );
}

export function DemoBadge({ text = 'Demo mode — sample content' }: { text?: string }) {
  return (
    <span className="badge-demo" title="Prepared fixture content shipped with the bundled sample. Not generated by Claude.">
      <FlaskConical size={13} aria-hidden="true" />
      {text}
    </span>
  );
}

export function ProgressBar({ value, label }: { value: number; label: string }) {
  const pct = Math.max(0, Math.min(100, Math.round(value * 100)));
  return (
    <div className="progress" role="progressbar" aria-label={label} aria-valuemin={0} aria-valuemax={100} aria-valuenow={pct}>
      <span style={{ width: `${pct}%` }} />
    </div>
  );
}

export function Skeleton({ height = 16, width = '100%' }: { height?: number; width?: number | string }) {
  return <div className="skeleton" style={{ height, width }} aria-hidden="true" />;
}
